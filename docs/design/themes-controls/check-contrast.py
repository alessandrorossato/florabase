"""Design-only evidence; no application dependency. Run from any directory."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PALETTES = json.loads((ROOT / 'palette-proposal.json').read_text())

def luminance(color):
    channels = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    linear = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in channels]
    return sum(a * b for a, b in zip(linear, (0.2126, 0.7152, 0.0722)))

def ratio(a, b):
    lo, hi = sorted((luminance(a), luminance(b)))
    return (hi + 0.05) / (lo + 0.05)

surfaces = ['background', 'surface', 'surface-subtle', 'surface-hover', 'primary-subtle']
rows = []
failures = []
for name, t in PALETTES.items():
    cases = {
        'Text (worst UI surface)': (min(ratio(t['text'], t[s]) for s in surfaces), 4.5),
        'Muted / placeholder (worst)': (min(ratio(t['text-muted'], t[s]) for s in surfaces), 4.5),
        'Primary label (normal / hover)': (min(ratio(t['on-primary'], t[s]) for s in ['primary', 'primary-hover']), 4.5),
        'Primary text / selected edge (worst)': (min(ratio(t['primary'], t[s]) for s in surfaces), 4.5),
        'Input border (worst)': (min(ratio(t['border-strong'], t[s]) for s in surfaces), 3),
        'Focus / info (worst)': (min(ratio(t['focus-ring'], t[s]) for s in surfaces), 4.5),
        'Success text (worst)': (min(ratio(t['success'], t[s]) for s in surfaces), 4.5),
        'Warning text (incl. warning-subtle)': (min(ratio(t['warning-text'], t[s]) for s in surfaces + ['warning-subtle']), 4.5),
        'Warning symbol (worst)': (min(ratio(t['warning'], t[s]) for s in surfaces), 3),
        'Danger text (incl. danger-subtle)': (min(ratio(t['danger'], t[s]) for s in surfaces + ['danger-subtle']), 4.5),
        'Tooltip text': (ratio(t['text'], t['surface']), 4.5),
        'Five comparison swatches on surface (worst)': (min(ratio(c, t['surface']) for c in t['comparison']), 3),
    }
    for label, (value, threshold) in cases.items():
        rows.append(f'| {name} | {label} | {value:.2f}:1 | {threshold}:1 | {"PASS" if value >= threshold else "FAIL"} |')
        if value < threshold:
            failures.append((name, label, value))
report = '# Calculated design contrast evidence\n\nGenerated by `python3 docs/design/themes-controls/check-contrast.py`.\n'
report += 'sRGB relative luminance, unrounded threshold comparison; display rounded to two decimals.\n\n'
report += '| Variant | Pair / minimum | Ratio | Required | Result |\n| --- | --- | --- | --- | --- |\n' + '\n'.join(rows) + '\n'
(ROOT / 'contrast-evidence.md').write_text(report)
print(f'{len(rows)} contrast cases; {len(failures)} failures')
for failure in failures:
    print(failure)
raise SystemExit(bool(failures))
