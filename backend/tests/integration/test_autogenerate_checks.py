import pytest
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import CheckConstraint, Engine

from alembic import command
from florabase.botanical_identities.model import BotanicalIdentity

pytestmark = pytest.mark.integration


def test_autogenerate_detects_added_named_check(database_engine: Engine) -> None:
    constraint = CheckConstraint("1 = 1", name="ck_dependency_autogenerate_probe")
    table = BotanicalIdentity.metadata.tables["botanical_identities"]
    table.append_constraint(constraint)
    try:
        with pytest.raises(AutogenerateDiffsDetected) as detected:
            command.check(Config("alembic.ini"))
        assert any(
            diff[0] == "add_constraint"
            and isinstance(diff[1], CheckConstraint)
            and diff[1].name == constraint.name
            for diff in detected.value.diffs
        )
    finally:
        table.constraints.remove(constraint)


def test_autogenerate_detects_removed_named_check(database_engine: Engine) -> None:
    table = BotanicalIdentity.metadata.tables["botanical_identities"]
    constraint = next(
        item
        for item in table.constraints
        if isinstance(item, CheckConstraint)
        and item.name == "ck_botanical_identities_scientific_name_length"
    )
    table.constraints.remove(constraint)
    try:
        with pytest.raises(AutogenerateDiffsDetected) as detected:
            command.check(Config("alembic.ini"))
        assert any(
            diff[0] == "remove_constraint"
            and isinstance(diff[1], CheckConstraint)
            and diff[1].name == constraint.name
            for diff in detected.value.diffs
        )
    finally:
        table.append_constraint(constraint)
